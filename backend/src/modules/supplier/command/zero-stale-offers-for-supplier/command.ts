/**
 * Остаток в ноль у предложений поставщика, которых больше нет в его выгрузке (карточки не удаляются, план 4.4.5):
 * - `synced_before` — полная выгрузка закончилась, всё, что не обновлено с её начала, — пропало;
 * - `variant_ids` — товар помечен в выгрузке удалённым: его варианты у этого поставщика.
 */
export type ZeroStaleOffersForSupplierCommand = {
  supplier_id: string;
  /** ISO-строка — начало запуска импорта. */
  synced_before?: string;
  variant_ids?: string[];
};
